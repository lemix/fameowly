/**
 * Generates lib/generated/plugin-slots.ts from plugin UI manifests.
 *
 * Each plugin declares its slots in extensions/plugins/<plugin>/ui-slots.json:
 *   { "<slot-id>": { "component": "components/foo", "inline": true } }
 *
 * Bundlers require literal import paths, so the loader map cannot be built at
 * runtime — this script emits it instead, which keeps core files untouched
 * when a plugin is added.
 *
 * Emits an empty map when ENABLE_PLUGINS=false or no plugins are present.
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const pluginsRoot = path.join(root, "extensions", "plugins");
const outDir = path.join(root, "lib", "generated");
const outFile = path.join(outDir, "plugin-slots.ts");

const SAFE_SEGMENT = /^[A-Za-z0-9._-]+$/;

/** Reject traversal and absolute paths before they reach a generated import */
function isSafeComponentPath(value) {
  if (typeof value !== "string" || value.length === 0) return false;
  return value
    .split("/")
    .every((seg) => SAFE_SEGMENT.test(seg) && seg !== "." && seg !== "..");
}

function collectSlots() {
  if (process.env.ENABLE_PLUGINS === "false") return [];
  if (!fs.existsSync(pluginsRoot)) return [];

  const slots = [];
  const seen = new Map();

  for (const pluginDir of fs.readdirSync(pluginsRoot).sort()) {
    const manifestPath = path.join(pluginsRoot, pluginDir, "ui-slots.json");
    if (!fs.existsSync(manifestPath)) continue;

    let manifest;
    try {
      manifest = JSON.parse(fs.readFileSync(manifestPath, "utf-8"));
    } catch (err) {
      throw new Error(`[plugin-slots] Invalid JSON in ${manifestPath}: ${err.message}`);
    }

    for (const [id, entry] of Object.entries(manifest)) {
      const component = typeof entry === "string" ? entry : entry?.component;
      if (!isSafeComponentPath(component)) {
        throw new Error(
          `[plugin-slots] Slot "${id}" in ${pluginDir} has an invalid component path.`,
        );
      }
      if (seen.has(id)) {
        throw new Error(
          `[plugin-slots] Slot id "${id}" is declared by both "${seen.get(id)}" and "${pluginDir}".`,
        );
      }
      seen.set(id, pluginDir);

      slots.push({
        id,
        importPath: `${pluginDir}/${component}`,
        inline: typeof entry === "object" && entry.inline === true,
      });
    }
  }

  return slots;
}

const slots = collectSlots();

const lines = [
  "// Auto-generated by scripts/generate-plugin-slots.js — do not edit.",
  "",
  "export type SlotLoader = () => Promise<Record<string, unknown>>;",
  "",
  "export const slotLoaders: Record<string, SlotLoader> = {",
  ...slots.map(
    (s) => `  ${JSON.stringify(s.id)}: () => import(${JSON.stringify(`@plugins/ext/${s.importPath}`)}),`,
  ),
  "};",
  "",
  "/** Slots rendered next to other controls must not show a block placeholder */",
  `export const inlineSlots: ReadonlySet<string> = new Set(${JSON.stringify(
    slots.filter((s) => s.inline).map((s) => s.id),
  )});`,
  "",
];

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, lines.join("\n"));

console.log(`[plugin-slots] Generated ${slots.length} slot(s) into lib/generated/plugin-slots.ts`);
